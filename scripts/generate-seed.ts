/**
 * Generates supabase/seed.sql from src/lib/products.ts so the database
 * starts with the same catalog as the site.
 *   npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { categories, products } from "../src/lib/products";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(",")}]::text[]`;

const lines: string[] = ["-- Generated by scripts/generate-seed.ts — do not edit by hand.", "begin;"];
categories.forEach((c, i) =>
  lines.push(
    `insert into public.categories (slug,label,grp,image_url,sort_order) values (${q(c.slug)},${q(c.label)},${q(c.group)},${q(c.image)},${i}) on conflict (slug) do update set label=excluded.label, grp=excluded.grp, image_url=excluded.image_url, sort_order=excluded.sort_order;`,
  ),
);
for (const p of products) {
  lines.push(
    `insert into public.products (slug,name,category_slug,price,compare_at,description,details,images,colors,is_new,featured,is_demo,price_to_confirm,created_at) values (${q(p.slug)},${q(p.name)},${q(p.category)},${p.price},${p.compareAt ?? "null"},${q(p.description)},${arr(p.details)},${arr(p.images)},${q(JSON.stringify(p.colors))}::jsonb,${!!p.isNew},${!!p.featured},${!!p.demo},${!!p.priceToConfirm},${q(p.createdAt)}) on conflict (slug) do nothing;`,
  );
  for (const s of p.sizes)
    lines.push(
      `insert into public.inventory (product_id,size,color,stock) select id,${q(s.label)},'',${s.stock} from public.products where slug=${q(p.slug)} on conflict do nothing;`,
    );
}
lines.push(
  "insert into public.coupons (code,type,value,min_subtotal,description) values ('FATTEST10','percent',10,0,'10% OFF') on conflict do nothing;",
  "commit;",
);
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log(`seed.sql: ${categories.length} categories, ${products.length} products`);
